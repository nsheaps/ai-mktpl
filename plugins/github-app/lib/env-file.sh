#!/usr/bin/env bash
# env-file.sh — Shared env file writer for the github-app plugin
#
# Provides write_runtime_env_file() which generates the runtime env file
# that is sourced via CLAUDE_ENV_FILE. Both github-token-init.sh (initial
# write) and token-check.sh (token refresh writes) call this function so
# the two files never drift out of sync.
#
# Required variables when called:
#   ENV_RUNTIME_FILE   — path to the runtime env file to write
#   TOKEN_FILE         — path to the token file
#
# Optional variables (sourced from environment):
#   GITHUB_APP_ID
#   GITHUB_INSTALLATION_ID
#   GH_CONFIG_DIR
#   GIT_AUTHOR_NAME
#   GIT_AUTHOR_EMAIL
#   GIT_COMMITTER_NAME
#   GIT_COMMITTER_EMAIL
#
# Git credential helper:
#   The plugin configures git via write_git_config_global(), which writes
#   `credential.helper = !gh auth git-credential` into the per-agent gitconfig.
#   gh reads GH_TOKEN from the process environment (always fresh via CLAUDE_ENV_FILE).
#   No script file is copied or installed.

if [ "${_ENV_FILE_LOADED:-}" = "true" ]; then return 0; fi
_ENV_FILE_LOADED="true"

# GIT_IDENTITY_FILE — path to the stable git identity file
# Written once at session start; never overwritten by token refresh.
# Uses CLAUDE_PLUGIN_DATA (per-agent) so multiple agents on the same machine
# don't stomp on each other's identity file.
GIT_IDENTITY_FILE="${CLAUDE_PLUGIN_DATA}/github-git-identity"

# _safe_val VALUE
#
# Escapes a value for safe embedding in a double-quoted shell assignment.
# Handles $, `, \, ", and newlines so that sourcing the resulting file
# cannot cause shell injection.
_safe_val() {
  local v="$1"
  # Replace backslash first to avoid double-escaping
  v="${v//\\/\\\\}"
  v="${v//\$/\\\$}"
  v="${v//\`/\\\`}"
  v="${v//\"/\\\"}"
  printf '%s' "$v"
}

# write_runtime_env_file TOKEN
#
# Writes the full runtime env file with token vars + credential pointers
# + git identity vars. All git identity vars default to empty if unset,
# which preserves them across token refreshes when they are already
# exported in the current process.
#
# Values are escaped with _safe_val() so that special characters in git
# config values, tokens, or paths cannot cause shell injection when the
# file is sourced.
#
# Args:
#   $1  — the raw token string
write_runtime_env_file() {
  local token="$1"
  mkdir -p "$(dirname "$ENV_RUNTIME_FILE")"

  # Use a quoted heredoc for the static header, then append variable lines
  # with explicit escaping via _safe_val.
  cat > "$ENV_RUNTIME_FILE" <<'ENVEOF'
# Auto-generated by github-app plugin — do not edit manually.
# This file is rewritten on every token refresh. Add nothing else here.
ENVEOF

  # Write each export using _safe_val to prevent injection
  {
    printf 'export GH_TOKEN="%s"\n' "$(_safe_val "$token")"
    printf 'export GITHUB_TOKEN="%s"\n' "$(_safe_val "$token")"
    printf 'export GITHUB_TOKEN_FILE="%s"\n' "$(_safe_val "$TOKEN_FILE")"
    printf 'export GITHUB_APP_ENV_FILE="%s"\n' "$(_safe_val "$ENV_RUNTIME_FILE")"
    printf 'export GITHUB_APP_ID="%s"\n' "$(_safe_val "${GITHUB_APP_ID:-}")"
    printf 'export GITHUB_INSTALLATION_ID="%s"\n' "$(_safe_val "${GITHUB_INSTALLATION_ID:-}")"
    printf 'export GIT_AUTHOR_NAME="%s"\n' "$(_safe_val "${GIT_AUTHOR_NAME:-}")"
    printf 'export GIT_AUTHOR_EMAIL="%s"\n' "$(_safe_val "${GIT_AUTHOR_EMAIL:-}")"
    printf 'export GIT_COMMITTER_NAME="%s"\n' "$(_safe_val "${GIT_COMMITTER_NAME:-}")"
    printf 'export GIT_COMMITTER_EMAIL="%s"\n' "$(_safe_val "${GIT_COMMITTER_EMAIL:-}")"
    echo "# Note: the identity defaults above preserve identity across token refreshes"
    echo "# only because CLAUDE_ENV_FILE is sourced before PreToolUse runs, so the vars"
    echo "# are already exported in the caller's environment. If token-check.sh is ever"
    echo "# run in a context that doesn't source CLAUDE_ENV_FILE first, these vars would"
    echo "# be written as empty strings and identity would be lost."
  } >> "$ENV_RUNTIME_FILE"

  # Preserve GH_CONFIG_DIR isolation across token refreshes
  [[ -n "${GH_CONFIG_DIR:-}" ]] && printf 'export GH_CONFIG_DIR="%s"\n' "$(_safe_val "$GH_CONFIG_DIR")" >> "$ENV_RUNTIME_FILE"
  chmod 600 "$ENV_RUNTIME_FILE"
}

# write_git_identity_file BOT_NAME BOT_EMAIL
#
# Writes a stable file containing only the git identity env vars.
# This file is NOT overwritten by token-check.sh, so identity survives
# even if the env file template drifts or is changed in the future.
#
# The file is sourced from CLAUDE_ENV_FILE after the runtime env file,
# so it takes precedence if the runtime env file somehow drops these vars.
#
# Values are escaped with _safe_val() to prevent shell injection from
# git config values containing special characters.
#
# Args:
#   $1  — bot name  (e.g. "my-app[bot]")
#   $2  — bot email (e.g. "12345+my-app[bot]@users.noreply.github.com")
write_git_identity_file() {
  local bot_name="$1"
  local bot_email="$2"
  mkdir -p "$(dirname "$GIT_IDENTITY_FILE")"

  cat > "$GIT_IDENTITY_FILE" <<'GITEOF'
# Stable git identity for GitHub App bot — written by github-app plugin at session start
# This file is NOT overwritten by token refreshes. Delete it to force a refresh.
GITEOF

  {
    printf 'export GIT_AUTHOR_NAME="%s"\n' "$(_safe_val "$bot_name")"
    printf 'export GIT_AUTHOR_EMAIL="%s"\n' "$(_safe_val "$bot_email")"
    printf 'export GIT_COMMITTER_NAME="%s"\n' "$(_safe_val "$bot_name")"
    printf 'export GIT_COMMITTER_EMAIL="%s"\n' "$(_safe_val "$bot_email")"
  } >> "$GIT_IDENTITY_FILE"

  chmod 600 "$GIT_IDENTITY_FILE"
}

# write_git_config_global
#
# Rewrites the isolated gitconfig with current identity from env vars
# (GIT_AUTHOR_NAME, GIT_AUTHOR_EMAIL) and installs a gh-based credential
# helper. Git reads GIT_CONFIG_GLOBAL on every operation, so changes take
# effect immediately on the next git command.
#
# The credential helper is written as `!gh auth git-credential` — no absolute
# path, no custom script file. gh reads $GH_TOKEN from the process environment
# (always fresh via CLAUDE_ENV_FILE) and returns the correct credentials.
# This is version-independent: the gitconfig entry never changes when gh upgrades.
#
# The target path is computed at call-time (not source-time) so the
# function always uses the current value of GIT_CONFIG_GLOBAL, avoiding
# order-dependent bugs when callers source this lib at different points.
#
# Guard: if gh is not on PATH, the function prints an error to stderr and returns 1.
# The caller (hook) runs with set -euo pipefail, so SessionStart will abort and
# surface the error rather than leaving gitconfig without a [credential] section.
write_git_config_global() {
  local bot_name="${GIT_AUTHOR_NAME:-}"
  local bot_email="${GIT_AUTHOR_EMAIL:-}"
  local target="${GIT_CONFIG_GLOBAL:-${CLAUDE_PLUGIN_DATA}/git/config}"

  [[ -n "$bot_name" && -n "$bot_email" ]] || return 0

  mkdir -p "$(dirname "$target")"

  cat > "$target" <<GCEOF
[user]
    name = ${bot_name}
    email = ${bot_email}
GCEOF

  if command -v gh >/dev/null 2>&1; then
    # gh auth git-credential reads $GH_TOKEN from env — no script file needed,
    # no versioned path embedded. The double-reset (helper = empty then helper = !gh)
    # clears any previously-configured credential helper before setting ours,
    # matching the pattern git itself uses when resetting helpers.
    cat >> "$target" <<'GCEOF'
[credential "https://github.com"]
    helper =
    helper = !gh auth git-credential
GCEOF
  else
    echo "write_git_config_global: gh not found on PATH — cannot configure credential.helper. Install gh (github.com/cli/cli) and ensure it is on PATH before starting a session." >&2
    return 1
  fi

  chmod 600 "$target"
}
